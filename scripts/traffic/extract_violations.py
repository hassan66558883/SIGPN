"""
Extracts the offence table from the official source PDF and writes the typed dataset
src/server/traffic/data/violations-source.ts.

Usage (Python 3 + PyMuPDF):
    python scripts/traffic/extract_violations.py docs/sources/TABLEAU-DES-INFRACTIONS-A-LA-CIRCULATION-ROUTIERE-ET-TAUX-D-AMENDE-FORFAITAIRES.pdf

Rules (legal fidelity):
  * names, classes, legal references and amounts are copied verbatim; only runs of whitespace are
    collapsed to one space (the PDF wraps cells over several lines);
  * nothing is corrected or completed — anomalies are only flagged in `sourceNote`.
"""
import hashlib, json, re, sys
import pymupdf

pdf_path = sys.argv[1]
sha = hashlib.sha256(open(pdf_path, "rb").read()).hexdigest()
norm = lambda s: re.sub(r"\s+", " ", s).strip()

doc = pymupdf.open(pdf_path)
category = "ROAD"
rows = []
for pi, page in enumerate(doc):
    for table in page.find_tables().tables:
        for raw in table.extract():
            cells = [norm(c) for c in raw if c and norm(c)]
            if not cells:
                continue
            joined = " ".join(cells)
            if cells[0].startswith("Infractions") and len(cells) >= 3 and "Classe" in cells[1]:
                continue
            if cells == ["forfaitaire"]:
                continue
            if "INFRACTIONS ADDITIONNELLES" in joined.upper():
                category = "CYCLE_MOTORCYCLE" if "CYCLES" in joined.upper() else "MOTO_TAXI"
                continue
            assert len(cells) == 4, (pi + 1, cells)
            rows.append({"page": pi + 1, "category": category, "name": cells[0], "classText": cells[1], "reference": cells[2], "amountText": cells[3]})

CLASS = {"2eme": "CLASS_2", "3eme": "CLASS_3", "4eme": "CLASS_4", "Délit": "DELIT"}
def amount(text):
    if "arbitrer" in text:
        return None
    m = re.fullmatch(r"(\d[\d ]*)\s*fcfa", text, re.I)
    assert m, text
    return int(m.group(1).replace(" ", ""))

# usual rate per class (mode) — only used to FLAG deviations, never to change them
from collections import Counter
usual = {}
for cls in ("2eme", "3eme", "4eme"):
    usual[cls] = Counter(amount(r["amountText"]) for r in rows if r["classText"] == cls).most_common(1)[0][0]

TYPO_NOTES = {
    "Défait de la licence spéciale de transport SMT": "Libellé conservé tel que dans la source (« Défait » — probable coquille pour « Défaut »).",
    "Mauvaise stationnement ou stationnement interdit": "Libellé conservé tel que dans la source (« Mauvaise stationnement »).",
    "Refus de serer sur le bord droit quant on veut quitter la chaussée par la droite": "Libellé conservé tel que dans la source (« serer », « quant »).",
    "Défaut de vitesse en substance transparente": "Libellé conservé tel que dans la source.",
    "Défaut de maitrise": "Référence conservée telle que dans la source (« A » à la place d’un numéro d’article).",
    "Défaut d’avertissements": "Référence conservée telle que dans la source (« 742 »).",
    "Dépassement à signaler lorsqu’il s’effectue du côté droit ou mauvaise": "Libellé apparemment tronqué dans la source (« ou mauvaise »), conservé tel quel.",
}

out = []
for i, r in enumerate(rows, 1):
    amt = amount(r["amountText"])
    notes = []
    if amt is None:
        notes.append("Délit : la source indique « Interdiction d’arbitrer » à la place d’un montant forfaitaire.")
    elif amt != usual[r["classText"]]:
        notes.append(f"Montant de la source ({amt:,} FCFA) différent du taux le plus fréquent de cette classe ({usual[r['classText']]:,} FCFA) : conservé tel quel.".replace(",", " "))
    if r["name"] in TYPO_NOTES:
        notes.append(TYPO_NOTES[r["name"]])
    if r["name"].startswith("Défaut de dispositif d’équipement d’une mototaxi"):
        notes.append("Parenthèse non refermée dans la source, conservée telle quelle.")
    out.append({
        "order": i, "code": f"TRF-{i:03d}", "page": r["page"], "category": r["category"], "name": r["name"],
        "classText": r["classText"], "offenceClass": CLASS[r["classText"]], "reference": r["reference"],
        "amountText": r["amountText"], "amountFcfa": amt, "sourceNote": " ".join(notes) or None,
    })

def ts(v):
    return json.dumps(v, ensure_ascii=False)

lines = [
    "/**",
    " * Offence table imported VERBATIM from the official document",
    " * « TABLEAU DES INFRACTIONS A LA CIRCULATION ROUTIERE ET TAUX D’AMENDE FORFAITAIRES ».",
    " * GENERATED by scripts/traffic/extract_violations.py — do not edit by hand.",
    " * Names, classes, legal references and amounts are NOT corrected; anomalies are only flagged in `sourceNote`.",
    " */",
    "export type TrafficCategoryCode = \"ROAD\" | \"CYCLE_MOTORCYCLE\" | \"MOTO_TAXI\";",
    "export type TrafficOffenceClassCode = \"CLASS_2\" | \"CLASS_3\" | \"CLASS_4\" | \"DELIT\";",
    "export type SourceViolation = { order: number; code: string; page: number; category: TrafficCategoryCode; name: string; classText: string; offenceClass: TrafficOffenceClassCode; reference: string; amountText: string; amountFcfa: number | null; sourceNote: string | null };",
    "",
    f"export const TRAFFIC_SOURCE_DOCUMENT = {{ title: \"TABLEAU DES INFRACTIONS A LA CIRCULATION ROUTIERE ET TAUX D’AMENDE FORFAITAIRES\", file: \"docs/sources/TABLEAU-DES-INFRACTIONS-A-LA-CIRCULATION-ROUTIERE-ET-TAUX-D-AMENDE-FORFAITAIRES.pdf\", sha256: \"{sha}\", pages: {len(doc)} }} as const;",
    "",
    "export const TRAFFIC_CATEGORIES_SOURCE = [",
    "  { code: \"ROAD\", name: \"Infractions routières\", sourceHeading: null, sortOrder: 1 },",
    "  { code: \"CYCLE_MOTORCYCLE\", name: \"Infractions relatives aux cycles et motocyclettes\", sourceHeading: \"INFRACTIONS ADDITIONNELLES RELATIVES AUX CYCLES ET MOTOCYCLES\", sortOrder: 2 },",
    "  { code: \"MOTO_TAXI\", name: \"Infractions relatives aux moto-taxis\", sourceHeading: \"INFRACTIONS ADDITIONNELLES RELATIVES AU MOTO-TAXIS\", sortOrder: 3 },",
    "] as const;",
    "",
    "export const TRAFFIC_VIOLATIONS_SOURCE: readonly SourceViolation[] = [",
]
for o in out:
    lines.append("  " + ts(o) + ",")
lines.append("];")
lines.append("")
open("src/server/traffic/data/violations-source.ts", "w", encoding="utf-8").write("\n".join(lines))
print("offences:", len(out), Counter(o["category"] for o in out), "usual rates:", usual)
print("flagged:", sum(1 for o in out if o["sourceNote"]))
